# -*- coding: utf-8 -*-
"""Soul Tier 81-500: testy struktury, bramek, istniejących bossów krypt.

Uruchamiaj po zaladowaniu katalogow w standardowej kolejnosci serwera.
Nie zapisuje kont graczy ani zadnych danych dyskowych.
"""
from __future__ import annotations

def run():
    count=0
    def ok(v,msg):
        nonlocal count
        assert v,msg
        count+=1
    from core import progression_600 as p
    from core.bootstrap_economy_professions import SOUL_TRIAL_QUEST_IDS
    from systems.dungeons_regions import is_crypt_boss_floor
    from world import dynamic_content  # ensure catalog bootstrap order
    from systems.content_registry import MOB_TEMPLATES, QUESTS
    ok(p.SOUL_MAX_TIER>=500,'historical tier catalog 1-500 missing')
    ok(len(p.SOUL_TIER_THRESHOLDS)>=500,'tier threshold length')
    ok(p.SOUL_TIER_THRESHOLDS[79]==800,'legacy Tier 80')
    ok(p.SOUL_TIER_THRESHOLDS[80]==810,'new Tier 81')
    ok(p.SOUL_TIER_THRESHOLDS[499]==5000,'historical Tier 500 threshold')
    for name in ('SOUL_TIER_THRESHOLDS','SOUL_TIER_POWER_BONUSES',
                 'SOUL_TIER_CLASS_BONUS_PERCENT','SOUL_TIER_DODGE_BONUS',
                 'SOUL_TIER_GUARDIAN_REDUCTION'):
        ok(len(getattr(p,name))>=500,'historical table length '+name)
    for tier in range(81,501):
        level=800+(tier-80)*10
        ok(p.SOUL_TIER_THRESHOLDS[tier-1]==level,f'level threshold {tier}')
        ok(SOUL_TRIAL_QUEST_IDS[tier]==f'soul_tier_{tier:02d}_trial',f'trial quest id {tier}')
        ok(bool(p.soul_tier_title_for_class(tier,'Wojownik')),f'tier name {tier}')
        ok(p.SOUL_TIER_POWER_BONUSES[tier-1]>=p.SOUL_TIER_POWER_BONUSES[tier-2],f'power increase {tier}')
        ok(0<=p.SOUL_TIER_GUARDIAN_REDUCTION[tier-1]<=65,f'guard no invuln {tier}')
        ok(is_crypt_boss_floor(level),f'floor has boss {tier}')
    for tier in (1,40,41,60,80,81,100,200,499,500):
        trait=p.soul_weapon_trait_for_tier_v11193(tier,'Wojownik')
        ok(bool(trait and trait['name'] and trait['effect']),f'soul trait {tier}')
    # Names for 81+ are generated by normal infinite-Crypt floor activation,
    # not inserted into the initial static mob catalog. Validate the quest
    # definitions and their exact target IDs; runtime lazy floor activation is
    # a separate integration test and must not be confused with this test.
    for floor in (800,810,1000,2000,5000):
        quest=QUESTS.get(f'soul_tier_{floor//10:02d}_trial')
        ok(bool(quest),f'soul trial quest {floor}')
        ok(quest.get('target')==f'crypt_boss_{floor}',f'soul trial target {floor}')
        ok(quest.get('unlocks_soul_tier')==floor//10,f'soul trial unlock {floor}')
    return count

if __name__=='__main__':
    print('ERA BEZ GRANIC SOUL TIERS: '+str(run())+' checks PASS',flush=True)
