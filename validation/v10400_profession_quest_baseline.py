# -*- coding: utf-8 -*-
"""Strict backward-compatibility contract using the ACTUAL v103 PREDEPLOY catalog.

The frozen file was generated by importing the v103.00.0 source ZIP in an
isolated loopback process. No generated placeholder IDs or fake quests.
"""
from __future__ import annotations
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent
FIXTURE = ROOT / 'v103_profession_quest_snapshot.json'


def check_baseline(quests, profession_groups, *, version="104.00.3"):
    historical = json.loads(FIXTURE.read_text(encoding='utf-8'))
    assert len(historical) == 2375, ('Zmieniona zamrożona baza v103', len(historical))
    current = {}
    for prof, group in profession_groups.items():
        for qid, quest in group:
            current[qid] = {
                'prof': prof,
                'name': str(quest.get('name', '')),
                'requ': quest.get('requires_quest'),
                'reward_profession': quest.get('reward_profession'),
                'required_profession': quest.get('required_profession'),
                'target': quest.get('target'),
            }
    lost = sorted(set(historical) - set(current))
    modified = sorted(qid for qid, old in historical.items()
                      if qid in current and current[qid] != old)
    new_ids = set(current) - set(historical)
    if lost or modified:
        raise AssertionError('Złamana zgodność profesji v103: brak=' + repr(lost[:20])
                             + ', zmienione=' + repr(modified[:20]))
    # The v103 snapshot is immutable. Each later release has its own exact
    # additive contract; v105 does not weaken the v104 140-ID audit.
    from validation.release_contracts import parse_version
    v105 = parse_version(version) >= (105, 0, 0)
    v104_ids = {qid for qid in new_ids if qid.startswith('v10400_')}
    if len(v104_ids) != 140:
        raise AssertionError('Nieoczekiwane nowe questy profesji v104 (oczekiwano 140): '
                             + repr(sorted(v104_ids)[:20]) + ', liczba=' + str(len(v104_ids)))
    if v105:
        from world.v10500_region_index import REGIONS
        expected_v105 = {
            f'v10500_{slug}_prof_{index:02d}'
            for slug, *_ in REGIONS for index in range(1, 16)
        }
        got_v105 = new_ids - v104_ids
        if got_v105 != expected_v105:
            raise AssertionError('Niezgodne 300 questow profesji v105: brak='
                                 + repr(sorted(expected_v105 - got_v105)[:20])
                                 + ', dodatkowe=' + repr(sorted(got_v105 - expected_v105)[:20]))
        expected_count = 2815
    else:
        if new_ids != v104_ids:
            raise AssertionError('Nieoczekiwane nowe questy profesji v104: '
                                 + repr(sorted(new_ids - v104_ids)[:20]))
        expected_count = 2515
    if len(current) != expected_count:
        raise AssertionError(f'Katalog profesji {version}: oczekiwano {expected_count}, jest {len(current)}')
    # Validate identifiers are truly installed in the whole registry too.
    if not set(current).issubset(quests):
        raise AssertionError('Nie wszystkie questy profesji istnieją w globalnym katalogu.')
    return {'historic_preserved': len(historical), 'new_v104': len(v104_ids),
            'new_v105': len(expected_v105) if v105 else 0,
            'total': len(current)}
